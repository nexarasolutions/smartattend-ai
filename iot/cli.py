from __future__ import annotations

import argparse
import getpass
import json
import os
import sys
import time

from iot.client import DeviceAPIError, DeviceClient
from iot.offline_queue import OfflineEventQueue


def _client(device_id: str, state_dir: str | None = None) -> DeviceClient:
    api_url = os.getenv("SMARTATTEND_API_URL", "")
    if not api_url:
        raise ValueError("Set SMARTATTEND_API_URL to the Manus application origin or its /api path.")
    return DeviceClient(
        api_url,
        device_id,
        state_dir=state_dir or os.getenv("SMARTATTEND_DEVICE_STATE_DIR"),
        allow_insecure_local_http=os.getenv("SMARTATTEND_ALLOW_INSECURE_LOCAL_HTTP", "false").lower() == "true",
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="SmartAttend Raspberry Pi edge client; never logs device credentials.")
    parser.add_argument("--device-id", default=os.getenv("SMARTATTEND_DEVICE_ID"))
    parser.add_argument("--state-dir", help="Optional local, permission-restricted state directory.")
    subcommands = parser.add_subparsers(dest="command", required=True)
    enroll = subcommands.add_parser("enroll", help="Use a one-time token generated by a SmartAttend Admin.")
    enroll.add_argument("--firmware-version", default=os.getenv("SMARTATTEND_FIRMWARE_VERSION", "unknown"))
    subcommands.add_parser("heartbeat", help="Send device health and retry queued attendance events once.")
    retry = subcommands.add_parser("retry", help="Retry due offline-queued attendance events once.")
    retry.add_argument("--limit", type=int, default=100)
    submit = subcommands.add_parser("submit", help="Submit a sensor observation; use after your sensor adapter produces an event.")
    submit.add_argument("--session-id", required=True)
    submit.add_argument("--roll-number", required=True)
    submit.add_argument("--status", choices=["Present", "Absent", "Late"], default="Present")
    submit.add_argument("--sensor-type", default="unspecified")
    loop = subcommands.add_parser("heartbeat-loop", help="Keep sending heartbeat and retrying the queue.")
    loop.add_argument("--interval-seconds", type=int, default=60)
    subcommands.add_parser("status", help="Query this authenticated device's server-side status.")
    subcommands.add_parser("queue-status", help="Show local queue counts without displaying event payloads.")
    args = parser.parse_args(argv)

    try:
        if args.command == "queue-status":
            state_dir = args.state_dir or os.getenv("SMARTATTEND_DEVICE_STATE_DIR")
            queue = OfflineEventQueue(f"{state_dir}/events.sqlite3" if state_dir else None)
            print(json.dumps(queue.counts(), sort_keys=True))
            return 0
        if not args.device_id:
            raise ValueError("Set SMARTATTEND_DEVICE_ID or pass --device-id before the subcommand.")
        client = _client(args.device_id, args.state_dir)
        if args.command == "enroll":
            token = getpass.getpass("One-time Admin enrollment token (input hidden): ").strip()
            if not token:
                raise ValueError("An enrollment token is required.")
            result = client.register(token, args.firmware_version)
        elif args.command == "heartbeat":
            result = client.heartbeat({"queue": client.queue.counts()})
        elif args.command == "status":
            result = client.status()
        elif args.command == "retry":
            result = client.retry_pending(max(1, min(args.limit, 1000)))
        elif args.command == "submit":
            result = client.submit_attendance(session_id=args.session_id, roll_number=args.roll_number, status=args.status, sensor_type=args.sensor_type)
        elif args.command == "heartbeat-loop":
            interval = max(15, min(args.interval_seconds, 3600))
            while True:
                try:
                    print(json.dumps(client.heartbeat({"queue": client.queue.counts()}), sort_keys=True), flush=True)
                except DeviceAPIError as error:
                    print(json.dumps({"heartbeat": "failed", "reason": str(error), "queue": client.queue.counts()}), file=sys.stderr, flush=True)
                time.sleep(interval)
        else:
            parser.error("Unknown command")
            return 2
    except (DeviceAPIError, ValueError, OSError) as error:
        print(f"SmartAttend edge client: {error}", file=sys.stderr)
        return 1
    print(json.dumps(result, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
